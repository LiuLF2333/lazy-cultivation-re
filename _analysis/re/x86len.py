"""x86-32 instruction length decoder (MSVC-oriented, covers SSE/SSE2)."""

PFX = set([0x2E,0x36,0x3E,0x26,0x64,0x65,0x66,0x67,0xF0,0xF2,0xF3])

# 1-byte opcodes with NO operand
OP_NONE = set([0x90,0x91,0x92,0x93,0x94,0x95,0x96,0x97,0x98,0x99,0x9B,0x9C,0x9D,0x9E,0x9F,
               0xC3,0xC9,0xCB,0xCC,0xCE,0xCF,0xF4,0xF5,0xF8,0xF9,0xFA,0xFB,0xFC,0xFD,
               0x27,0x2F,0x37,0x3F,0x60,0x61,0x9A if False else 0x90])
OP_NONE |= set(range(0x40,0x50)) | set(range(0x50,0x58)) | set(range(0x58,0x60))
# string ops (movs/cmps/stos/lods/scas) - no operands
OP_NONE |= set([0xA4,0xA5,0xA6,0xA7,0xAA,0xAB,0xAC,0xAD,0xAE,0xAF])
# ins/outs/in/out - no operands
OP_NONE |= set([0x6C,0x6D,0x6E,0x6F,0xEC,0xED,0xEE,0xEF])
OP_NONE |= set([0xC9,0xCB])

# 1-byte opcodes with modrm, no immediate
OP_MODRM = set()
for b in range(0x00,0x40): OP_MODRM.add(b)          # arith
OP_MODRM |= set([0x62,0x63,0x84,0x85,0x86,0x87,0x88,0x89,0x8A,0x8B,0x8C,0x8D,0x8E,0x8F,
                 0xD0,0xD1,0xD2,0xD3,0xFE,0xFF,0x8F])
OP_MODRM |= set(range(0x00,0x40))

def _imm_for_group3(reg):
    return 1 if reg in (0,1) else 0

def modrm_extent(d, i):
    """Given index of modrm byte, return bytes consumed by modrm+sib+disp."""
    if i >= len(d): return 0
    m = d[i]; mod = m>>6; rm = m&7
    n = 1
    if mod != 3:
        if rm == 4:
            if i+n >= len(d): return n
            sib = d[i+n]; base = sib & 7; n += 1
            if mod == 0 and base == 5: n += 4
        elif mod == 0 and rm == 5:
            n += 4
        if mod == 1: n += 1
        elif mod == 2: n += 4
    return n

def insn_len(d, off):
    i = off; n = len(d)
    if i >= n: return 0
    while i < n and d[i] in PFX:
        i += 1
        if i-off > 8: return 0
    if i >= n: return 0
    op = d[i]; i += 1
    # ---- 1-byte ----
    if op == 0x0F:
        if i >= n: return 0
        o2 = d[i]; i += 1
        if 0x80 <= o2 <= 0x8F: return i-off+4
        if o2 in (0xA4,0xAC,0xA5,0xAD): return i-off+1 if o2 in (0xA4,0xAC) else i-off
        if o2 in (0xA2,0x31,0x30,0x32,0x33,0x34,0x35,0x0B,0x0E,0x05,0x06,0x07,0x08,0x09,0x77,0xAE):
            if o2 == 0xAE: return i-off+modrm_extent(d,i)
            return i-off
        if o2 == 0xBA: return i-off+modrm_extent(d,i)+1
        if o2 == 0x70 or o2 == 0xC7 or o2 == 0xC8 or o2 == 0xC9:
            if o2 == 0x70: return i-off+modrm_extent(d,i)+1
            return i-off
        if o2 in (0x1F,0x18,0x19,0x1A,0x1B,0x1C,0x1D,0x1E,0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,
                  0x28,0x29,0x2A,0x2B,0x2C,0x2D,0x2E,0x2F,0x50,0x51,0x52,0x53,0x54,0x55,0x56,0x57,
                  0x58,0x59,0x5A,0x5B,0x5C,0x5D,0x5E,0x5F,0x60,0x61,0x62,0x63,0x64,0x65,0x66,0x67,
                  0x68,0x69,0x6A,0x6B,0x6C,0x6D,0x6E,0x6F,0x70,0x71,0x72,0x73,0x74,0x75,0x76,
                  0x90,0x91,0x92,0x93,0x94,0x95,0x96,0x97,0x98,0x99,0x9A,0x9B,0x9C,0x9D,0x9E,0x9F,
                  0xAF,0xB0,0xB1,0xB2,0xB3,0xB4,0xB5,0xB6,0xB7,0xB8,0xB9,0xBA,0xBB,0xBC,0xBD,0xBE,0xBF,
                  0xC0,0xC1,0xC2,0xC3,0xC4,0xC5,0xC6,0xCA,0xCB,0xCC,0xCD,0xCE,0xCF,0xD0,0xD1,0xD2,0xD3,
                  0xD4,0xD5,0xD6,0xD7,0xD8,0xD9,0xDA,0xDB,0xDC,0xDD,0xDE,0xDF,0xE0,0xE1,0xE2,0xE3,0xE4,
                  0xE5,0xE6,0xE7,0xE8,0xE9,0xEA,0xEB,0xEC,0xED,0xEE,0xEF,0xF0,0xF1,0xF2,0xF3,0xF4,0xF5,
                  0xF6,0xF7,0xF8,0xF9,0xFA,0xFB,0xFC,0xFD,0xFE,0xFF,0x40,0x41,0x42,0x43,0x44,0x45,0x46,
                  0x47,0x48,0x49,0x4A,0x4B,0x4C,0x4D,0x4E,0x4F):
            return i-off+modrm_extent(d,i)
        return i-off+1
    if op in OP_NONE: return i-off
    if 0xB0 <= op <= 0xB7: return i-off+1
    if 0xB8 <= op <= 0xBF: return i-off+4
    if 0x70 <= op <= 0x7F: return i-off+1
    if op == 0x6A: return i-off+1
    if op == 0x68: return i-off+4
    if op in (0xE8,0xE9): return i-off+4
    if op in (0xEB,0xE0,0xE1,0xE2,0xE3): return i-off+1
    if op in (0xC2,0xCA): return i-off+2
    if op == 0xCD: return i-off+1
    if op == 0xA8: return i-off+1
    if op == 0xA9: return i-off+4
    if op in (0x04,0x0C,0x14,0x1C,0x24,0x2C,0x34,0x3C): return i-off+1
    if op in (0x05,0x0D,0x15,0x1D,0x25,0x2D,0x35,0x3D): return i-off+4
    if op in (0xA0,0xA1,0xA2,0xA3): return i-off+4
    # ---- x87 FPU: D8-DF all take a modrm byte ----
    if 0xD8 <= op <= 0xDF: return i-off+modrm_extent(d,i)
    if op == 0xF6: 
        e = modrm_extent(d,i)
        reg = (d[i]>>3)&7 if i < n else 0
        return i-off+e+(1 if reg in (0,1) else 0)
    if op == 0xF7:
        e = modrm_extent(d,i)
        reg = (d[i]>>3)&7 if i < n else 0
        return i-off+e+(4 if reg in (0,1) else 0)
    if op == 0xC6: return i-off+modrm_extent(d,i)+1
    if op == 0xC7: return i-off+modrm_extent(d,i)+4
    if op in (0x80,0x83): return i-off+modrm_extent(d,i)+1
    if op == 0x81: return i-off+modrm_extent(d,i)+4
    if op == 0x69: return i-off+modrm_extent(d,i)+4
    if op == 0x6B: return i-off+modrm_extent(d,i)+1
    if op in (0xC0,0xC1): return i-off+modrm_extent(d,i)+1
    if op in OP_MODRM: return i-off+modrm_extent(d,i)
    return 0
